#!/usr/bin/env python3
"""Generate the simulator lock-image fixture from a 250x122 source image.

The device stores a 4000-byte, 250x128 1bpp image. Visible rows are source
rows 6..127. Source bit 1 means black. This script converts the source to
1bpp on a white background, adds "图片锁屏示例" at the bottom,
prepends six black rows, and writes both the C header and a preview PNG of
the visible frame.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H = 250, 122
SRC_H = 128
TEXT = "图片锁屏示例"

CJK_CANDIDATES = [
    "/usr/share/fonts/noto-cjk/NotoSansCJK-Medium.ttc",
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc",
    "/usr/share/fonts/truetype/noto/NotoSansCJK-Medium.ttc",
]
CJK_INDEX = 2


def cjk_font(size: int) -> ImageFont.FreeTypeFont:
    for path in CJK_CANDIDATES:
        if Path(path).exists():
            return ImageFont.truetype(path, size, index=CJK_INDEX)
    raise SystemExit("Noto Sans CJK SC not found")


def build_visible(src: Path) -> Image.Image:
    im = Image.open(src).convert("RGBA")
    if im.size != (W, H):
        raise SystemExit(f"{src}: expected {W}x{H}, got {im.size}")

    # The artwork is a transparent sticker. Put it on white first; converting
    # straight to L would turn the transparent pixels black.
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    im = Image.alpha_composite(bg, im).convert("L")
    im = im.point(lambda p: 255 if p > 128 else 0)

    # Text is rendered at 4x, then reduced and thresholded so the strokes
    # survive the 1bpp conversion. Black text on the white background.
    s = 4
    layer = Image.new("L", (W * s, H * s), 255)
    d = ImageDraw.Draw(layer)
    d.text((W * s // 2, 108 * s), TEXT, font=cjk_font(16 * s), fill=0,
           anchor="mm")
    layer = (
        layer.resize((W, H), Image.Resampling.LANCZOS)
        .point(lambda p: 0 if p < 128 else 255)
    )
    im.paste(0, mask=layer.point(lambda p: 255 if p == 0 else 0))
    return im


def pack(visible: Image.Image) -> bytes:
    out = bytearray(W * SRC_H // 8)
    for y in range(SRC_H):
        for x in range(W):
            # Source rows 0..5 are the cropped top; they are black.
            black = True
            if y >= 6:
                black = visible.getpixel((x, y - 6)) == 0
            if black:
                out[(y >> 3) * W + x] |= 1 << (y & 7)
    return bytes(out)


def preview(visible: Image.Image, out: Path) -> None:
    vis = visible.copy()
    out.parent.mkdir(parents=True, exist_ok=True)
    vis.resize((W * 3, H * 3), Image.Resampling.NEAREST).save(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="tools/assets/lock_demo_src.png", type=Path)
    ap.add_argument("--header", default="sim/lock_demo.h", type=Path)
    ap.add_argument("--preview", default="/tmp/lock_demo_preview.png", type=Path)
    args = ap.parse_args()

    visible = build_visible(args.src)
    data = pack(visible)

    lines = [
        "/* Generated by tools/gen_lock_demo.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint8_t k_lock_demo[4000] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(lines) + "\n")

    preview(visible, args.preview)
    print(f"{args.header} ({len(data)} B)")
    print(f"{args.preview} {W * 3}x{H * 3}")


if __name__ == "__main__":
    main()
