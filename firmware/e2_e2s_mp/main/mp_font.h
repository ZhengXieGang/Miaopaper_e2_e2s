#pragma once
/* mp_font.h — Miaopaper's Adafruit-GFX fonts + HZK16 drawing on the 250x122
 * logical frame. Coordinates are already in E2S logical space (the reference
 * renders into a 250x128 canvas with the top 6 rows hidden; callers subtract
 * 6 with MP_Y()).
 */
#include <stdint.h>

/* Adafruit GFX compatible structures (same layout as OneBitDisplay.h). */
typedef struct {
    uint16_t bitmapOffset;
    uint8_t width;
    uint8_t height;
    uint8_t xAdvance;
    int8_t xOffset;
    int8_t yOffset;
} GFXglyph;

typedef struct {
    uint8_t *bitmap;
    GFXglyph *glyph;
    uint8_t first;
    uint8_t last;
    uint8_t yAdvance;
} GFXfont;

extern const GFXfont Dialog_plain_16;
/* Inter (SIL OFL 1.1): generated by tools/gen_ui_font.py. Inter_UI_16 is the
 * UI's proportional ASCII face; Inter_Num_26 is the medium tabular numeral
 * face for TIME_SET and JUMP; Inter_Clock_66 is the large tabular clock.
 * The old DSEG14/Special Elite/Dialog_plain_16_zh headers are no longer
 * compiled (DSEG was replaced by Inter in UI v2). */
extern const GFXfont Inter_UI_16;
extern const GFXfont Inter_Num_26;
extern const GFXfont Inter_Clock_66;

int mp_gfx_width(const GFXfont *font, const char *s);
void mp_gfx_text(uint8_t *fb, const GFXfont *font, int x, int baseline,
                 const char *s);
/* black=1 draws ink, black=0 erases (white text on an inverse row). */
void mp_gfx_text_color(uint8_t *fb, const GFXfont *font, int x, int baseline,
                       const char *s, int black);

int mp_text_width(const char *s, uint8_t enc);
void mp_text_draw(uint8_t *fb, const char *s, uint8_t enc, int x, int baseline,
                  int max_w);
void mp_text_draw_color(uint8_t *fb, const char *s, uint8_t enc, int x,
                        int baseline, int max_w, int black);

void mp_hz_char(uint8_t *fb, uint8_t hi, uint8_t lo, int x, int y);
void mp_hz_char_color(uint8_t *fb, uint8_t hi, uint8_t lo, int x, int y,
                      int black);

/* Miaopaper canvas (250x128, visible from y=6) -> E2S logical frame (250x122). */
#define MP_Y(y) ((y) - 6)
